// Build src/vo-data.ts from public/vo/sceneN.vtt and the mp3 durations. Run after regenerating voiceover.
import fs from "node:fs";
import { execFileSync } from "node:child_process";
const sec = (t) => { const [h, m, r] = t.replace(",", ".").split(":"); return +h * 3600 + +m * 60 + +r; };
const out = {};
for (let i = 1; i <= 7; i++) {
  const vtt = fs.readFileSync(`public/vo/scene${i}.vtt`, "utf8").trim().split(/\n\s*\n/);
  const cues = vtt.map(b => b.split("\n")).filter(l => l.some(x => x.includes("-->"))).map(l => {
    const k = l.findIndex(x => x.includes("-->")); const [a, b] = l[k].split(" --> ");
    return { from: +sec(a).toFixed(2), to: +sec(b).toFixed(2), text: l.slice(k + 1).join(" ").trim() };
  });
  const dur = +execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", `public/vo/scene${i}.mp3`]).toString().trim();
  out[`scene${i}`] = { duration: dur, cues };
}
fs.writeFileSync("src/vo-data.ts", "// Generated by scripts-vo.mjs. Do not edit by hand.\nexport const VO = " + JSON.stringify(out, null, 1) + " as const;\n");
for (const [k, v] of Object.entries(out)) console.log(k, v.duration, v.cues.length, "cues");
