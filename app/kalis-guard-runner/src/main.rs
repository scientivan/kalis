mod signing_keys_host {
    wit_bindgen::generate!({ world: "signing-keys-host", path: "wit" });
}

/// Sign with the TEE-held key on OutLayer. Returns (public key, signature).
#[cfg(target_family = "wasm")]
fn tee_sign(message: &[u8]) -> Result<(Vec<u8>, Vec<u8>), String> {
    use signing_keys_host::outlayer::signing_keys::api;
    Ok((api::public_key("completion", None)?, api::sign("completion", None, message)?))
}

/// Native builds (local tests only) sign with a fixed throwaway key.
#[cfg(not(target_family = "wasm"))]
fn tee_sign(message: &[u8]) -> Result<(Vec<u8>, Vec<u8>), String> {
    use ed25519_dalek::{Signer, SigningKey};
    let k = SigningKey::from_bytes(&[7u8; 32]);
    Ok((k.verifying_key().to_bytes().to_vec(), k.sign(message).to_bytes().to_vec()))
}

