/// OutLayer manifest: network only to NEAR AI Cloud, and one ed25519 signing key that the
/// keystore derives inside the TEE for this project, the same for every caller
/// ("caller": "none"). It signs only completion records this module composes.
const MANIFEST: &[u8] = br#"{"capabilities":{"network":[{"host":"cloud-api.near.ai","timeout_secs":120},{"host":"rpc.testnet.near.org","timeout_secs":30}]},"signing_keys":[{"path":"completion","type":"ed25519","caller":"none"}]}"#;
#[cfg(target_family = "wasm")]
#[used]
#[unsafe(link_section = "outlayer.manifest")]
static OUTLAYER_MANIFEST: [u8; MANIFEST.len()] = {
    let mut out = [0u8; MANIFEST.len()];
    let mut i = 0;
    while i < MANIFEST.len() { out[i] = MANIFEST[i]; i += 1; }
    out
};

/// Prefix of every signed completion record, so the key never signs bytes a
/// caller chose freely.
const COMPLETION_PREFIX: &str = "kalis-completion:v1:";

