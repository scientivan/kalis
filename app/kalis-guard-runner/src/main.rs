//! Kalis guard runner: a copy of the Kalis runner (option B) for the AI Security guard methods. The only
//! difference is a second allowlisted host, `rpc.testnet.near.org`, used by `chain.rs` for read-only
//! view calls before the method runs. Separate OutLayer project, so its seal key and completion key are its own.
//!
//! Kalis runner (option B) for OutLayer.
//!
//! Runs a seller's method on a buyer's data inside the OutLayer TEE so that
//! neither the operator, the public chain, the seller nor the buyer sees what
//! they are not owed:
//! - Outer box: this program embeds an OutLayer manifest whose network
//!   allowlist holds one host, `cloud-api.near.ai`, so the worker refuses every
//!   other outbound connection.
//! - Inner box: the seller's method is a WASM guest run by the `wasmi`
//!   interpreter. Its only possible import is `kalis.ai_chat`, which the runner
//!   serves itself, and only for the models the method manifest lists (see
//!   `ai.rs`). The method never gets a socket, storage or the chain.
//! - Two method kinds (manifest `kind`): `wasm` (default) is seller code as
//!   above; `prompt` is a seller prompt the runner sends to an allowed private
//!   model with the buyer data, then checks the answer does not quote the
//!   prompt.
//! - Sealing: both the method and the data arrive encrypted to an X25519 key
//!   that exists only inside the TEE (`PROTECTED_SEAL_KEY`, generated by the
//!   OutLayer keystore and locked to this build). The answer is encrypted back
//!   to the buyer's one-time key.
//! - Leak padding: the guest always gets the same fuel budget and the rest is
//!   burned, and the answer plaintext is padded to a fixed length, so the
//!   public instruction count and output size do not depend on the data.
//!
//! Input (stdin JSON):
//!   {"cmd":"pubkey"}
//!   {"cmd":"run","run_id":<escrow run id>,"manifest":<manifest file text>,"method":<sealed>,"data":<sealed>}
//!
//! Besides the sealed answer, every run returns a public completion record
//! signed by a TEE-held key: run id, whether every stage succeeded, and the
//! hashes of the method, manifest and buyer data. The escrow contract pays out
//! or refunds on that record alone.
//!   <sealed> = {"epk":<b64 32B>,"nonce":<b64 12B>,"ct":<b64>}
//! The method plaintext is the guest WASM. The data plaintext is the case JSON.
//! The manifest is public; its SHA-256 is reported so the buyer can match it
//! with the registry, and its `steps` list is what the method must report.
//!
//! The sealed answer carries an execution report: the seven runner stages,
//! each marked ok, and the method's own step list compared with the manifest
//! (missing, failed or undeclared steps are flagged). Method steps are the
//! seller's own claims about what its code did; the runner can only check
//! that they were all reported and all marked ok.

